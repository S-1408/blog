import { z } from "zod";

/** Lowercase letters, numbers and single hyphens, e.g. "the-art-of-noticing". */
export const SlugSchema = z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, "Invalid slug");

export const AuthorSchema = z.object({
  name: z.string().min(1),
});

/** A post as returned in list responses (no body). */
export const PostSummarySchema = z.object({
  slug: SlugSchema,
  title: z.string().min(1),
  description: z.string().min(1),
  category: z.string().min(1),
  /** ISO 8601 timestamp, e.g. "2025-03-18T00:00:00.000Z". */
  isoDate: z.iso.datetime(),
  /** Display date formatted by the API in UTC, e.g. "Mar 18, 2025". */
  date: z.string().min(1),
  readingTime: z.number().int().positive(),
  /** 1-based position in the newest-first list of all posts. */
  number: z.number().int().positive(),
});

/** A full post as returned by GET /api/posts/:slug. */
export const PostSchema = PostSummarySchema.extend({
  author: AuthorSchema,
  /** Original Markdown source. */
  content: z.string(),
  /** Server-rendered HTML generated by the API from the Markdown. */
  contentHtml: z.string(),
});

/**
 * Posts have a single `category`; the blog presents it as a tag.
 * `slug` is derived from `name` with {@link tagSlug}.
 */
export const TagSchema = z.object({
  name: z.string().min(1),
  slug: SlugSchema,
});

export type Author = z.infer<typeof AuthorSchema>;
export type PostSummary = z.infer<typeof PostSummarySchema>;
export type Post = z.infer<typeof PostSchema>;
export type Tag = z.infer<typeof TagSchema>;

export function tagSlug(name: string): string {
  return name
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}
